/**
 * 자유도 `df`의 유의수준 p=0.001 임계값을 돌려준다. 1~255의 정수가 아니면 `RangeError`를 던진다.
 * 자유도는 (칸 수 - 1)이다. 예: 문자 집합 크기 62는 61, 바이트 256칸은 255.
 */
export function chiSquareCritical(df: number): number {
  const value = Number.isInteger(df) ? CRITICAL_VALUES_P001[df - 1] : undefined;
  if (value === undefined) {
    throw new RangeError(
      `자유도는 1~${CRITICAL_VALUES_P001.length}의 정수여야 한다: ${df}`,
    );
  }
  return value;
}

/** 합계가 같은지 볼 때 허용하는 상대 오차. 부동소수점 누적 오차만 통과시킨다. */
const SUM_TOLERANCE = 1e-9;

/**
 * 관측 빈도 `observed`의 카이제곱 통계량 `Σ (관측 - 기대)² / 기대`를 돌려준다.
 * `expected`는 칸마다의 기대 빈도이며 생략하면 합계를 칸 수로 나눈 균등 분포다. 자유도는 `observed.length - 1`이다.
 * 표본이 없거나 기대가 비정상이면 통계량이 0이나 NaN이 되어 통계 테스트가 검증 없이 통과하므로 `RangeError`로 막는다.
 * 관측 합계와 기대 합계도 같아야 한다. 기대를 확률로 넘기는 실수를 잡는다.
 */
export function chiSquare(
  observed: readonly number[],
  expected?: readonly number[],
): number {
  if (observed.length < 2) {
    throw new RangeError("카이제곱 통계량은 칸이 2개 이상이어야 한다");
  }
  if (!observed.every((count) => Number.isFinite(count) && count >= 0)) {
    throw new RangeError("관측 빈도는 0 이상의 유한한 수여야 한다");
  }
  const total = sum(observed);
  const expectedCounts =
    expected ?? observed.map(() => total / observed.length);
  if (expectedCounts.length !== observed.length) {
    throw new RangeError("기대 빈도의 칸 수가 관측 빈도와 다르다");
  }
  if (!expectedCounts.every((count) => Number.isFinite(count) && count > 0)) {
    throw new RangeError("기대 빈도는 0보다 큰 유한한 수여야 한다");
  }
  if (Math.abs(sum(expectedCounts) - total) > SUM_TOLERANCE * total) {
    throw new RangeError("기대 빈도의 합계가 관측 빈도의 합계와 다르다");
  }

  return observed.reduce((statistic, count, i) => {
    const e = expectedCounts[i]!;
    return statistic + (count - e) ** 2 / e;
  }, 0);
}

/** 숫자 배열의 합. */
function sum(values: readonly number[]): number {
  return values.reduce((total, value) => total + value, 0);
}
